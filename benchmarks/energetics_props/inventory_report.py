"""Render `INVENTORY.md` from `inventory.json`, and refuse an inventory that has a count without a locator.

    python benchmarks/energetics_props/inventory_report.py            # rewrite INVENTORY.md
    python benchmarks/energetics_props/inventory_report.py --check    # exit 1 if INVENTORY.md is not what the JSON renders

The numbers in `inventory.json` were produced by the scripts under `inventory_scripts/` (text-layer counts, each with
a hand check recorded beside it) or read by hand off a named table; the JSON says which for every count. This module
renders them and validates their shape: a count with no locator, no method, or a negative value is an error, because a
count nobody can find on a page is the thing this inventory exists to prevent. It reads no PDF and no label.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
JSON_PATH = HERE / "inventory.json"
MD_PATH = HERE / "INVENTORY.md"

#: The properties a count may be about. Closed, so a typo cannot create a column.
PROPERTIES = (
    "melting_point", "decomposition_temperature", "crystal_density", "other_density", "enthalpy_formation",
    "enthalpy_sublimation", "enthalpy_fusion", "entries",
)
#: How a number was obtained.
METHODS = ("script", "table_read_by_hand", "regex_text_layer", "hand_count")


class InventoryError(ValueError):
    pass


def validate(inv: dict) -> None:
    """Raise `InventoryError` for a malformed inventory (a count without its locator, an unknown property...)."""
    if inv.get("schema_version") != 1:
        raise InventoryError("schema_version must be 1")
    seen = set()
    for src in inv["sources"]:
        sid = src.get("id")
        if not sid or sid in seen:
            raise InventoryError(f"source id missing or duplicated: {sid!r}")
        seen.add(sid)
        for key in ("title", "files", "held", "structure"):
            if key not in src:
                raise InventoryError(f"{sid}: missing {key!r}")
        for c in src.get("counts", []):
            where = f"{sid}/{c.get('property')}/{c.get('what')}"
            if c.get("property") not in PROPERTIES:
                raise InventoryError(f"{where}: unknown property")
            if not isinstance(c.get("n"), int) or isinstance(c.get("n"), bool) or c["n"] < 0:
                raise InventoryError(f"{where}: n must be a non-negative integer")
            if not str(c.get("locator", "")).strip():
                raise InventoryError(f"{where}: a count needs a locator (page, table or entry range)")
            if c.get("method") not in METHODS:
                raise InventoryError(f"{where}: method must be one of {METHODS}")
            if not str(c.get("what", "")).strip():
                raise InventoryError(f"{where}: a count must say what it counts")
        for e in src.get("printed_errors", []):
            if not str(e.get("locator", "")).strip() or not str(e.get("what", "")).strip():
                raise InventoryError(f"{sid}: a printed error needs a locator and a description")
    for nh in inv.get("not_held", []):
        if not nh.get("what") or not nh.get("why"):
            raise InventoryError("a not-held item needs what and why")
    for ub in inv.get("upper_bounds", []):
        if not (isinstance(ub.get("n"), int) and isinstance(ub.get("n_largest"), int) and 0 <= ub["n_largest"] <= ub["n"]) or not ub.get("basis"):
            raise InventoryError(f"upper bound for {ub.get('property')!r} needs integer n >= n_largest >= 0 and a basis")


def _table(headers: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c).replace("|", "/") for c in r) + " |" for r in rows]
    return out


def render(inv: dict) -> str:
    validate(inv)
    L: list[str] = []
    L.append("# Energetic-materials evidence inventory (Phase B)")
    L.append("")
    L.append(
        f"Generated by `benchmarks/energetics_props/inventory_report.py` from `inventory.json` (counted {inv['counted_on']}); "
        "every number below is read from that file, none is typed. The design is in `PREREGISTRATION.md`. "
        "**No corpus has been built and no method scored.** This inventory holds counts and locators: it was a counting "
        "stage, not a verdict on the sources. The values themselves are read from the held books and papers and quoted "
        "as facts with their pages (see `PETN_EVIDENCE.md` for the first such pass); a bulk corpus stays beside the library."
    )
    L.append("")
    L.append("## 1. How to read the counts")
    L.append("")
    for line in inv["how_to_read"]:
        L.append(f"* {line}")
    L.append("")
    L.append("## 2. Sources and what each is")
    L.append("")
    rows = []
    for s in inv["sources"]:
        rows.append([s["id"], s["title"], "yes" if s["held"] else "NO", s["structure"]])
    L += _table(["id", "source", "held", "structure"], rows)
    L.append("")
    L.append("## 3. Counts by source and property (entries or rows that print a numeric value, before identity)")
    L.append("")
    for s in inv["sources"]:
        counts = s.get("counts", [])
        if not counts:
            continue
        L.append(f"### {s['id']}")
        L.append("")
        L += _table(
            ["property", "what is counted", "n", "locator", "how"],
            [[c["property"], c["what"], c["n"], c["locator"], c["method"] + (f"; {c['error']}" if c.get("error") else "")] for c in counts],
        )
        if s.get("labels"):
            L.append("")
            L.append(f"*Labels:* {s['labels']}")
        if s.get("provenance"):
            L.append("")
            L.append(f"*Provenance of values:* {s['provenance']}")
        if s.get("text_layer"):
            L.append("")
            L.append(f"*Text layer:* {s['text_layer']}")
        if s.get("hand_check"):
            L.append("")
            L.append(f"*Hand check:* {s['hand_check']}")
        L.append("")
    L.append("## 4. Printed errors and inconsistencies found while counting")
    L.append("")
    L.append(
        "Found by comparing sources or reading the rendered page; each is a test case for the label-error rules of "
        "`PREREGISTRATION.md` section 8. Reported by locator, not reproduced."
    )
    L.append("")
    err_rows = [[s["id"], e["locator"], e["what"], e.get("checked", "")] for s in inv["sources"] for e in s.get("printed_errors", [])]
    L += _table(["source", "locator", "what", "checked on the page"], err_rows)
    L.append("")
    L.append("## 5. Cross-source agreement on well-known compounds")
    L.append("")
    cs = inv.get("cross_source", {})
    L.append(cs.get("note", ""))
    L.append("")
    if cs.get("rows"):
        L += _table(cs["columns"], cs["rows"])
        L.append("")
    L.append("## 6. Held data that is usable as it stands")
    L.append("")
    L += _table(
        ["item", "n", "what it holds", "locator", "limit"],
        [[d["item"], d["n"], d["holds"], d["locator"], d["limit"]] for d in inv.get("small_sources", [])],
    )
    L.append("")
    L.append("## 7. Upper bounds on usable entities, and what they allow")
    L.append("")
    L.append(inv.get("upper_bounds_note", ""))
    L.append("")
    L += _table(
        ["property", "ceiling (sum over sources)", "largest single source", "basis"],
        [[u["property"], u["n"], u["n_largest"], u["basis"]] for u in inv.get("upper_bounds", [])],
    )
    L.append("")
    L.append("## 8. Not held, not counted")
    L.append("")
    L += _table(["what", "why it is not counted"], [[n["what"], n["why"]] for n in inv.get("not_held", [])])
    L.append("")
    return "\n".join(L)


def main(argv: list[str]) -> int:
    inv = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    text = render(inv)
    if "--check" in argv:
        if not MD_PATH.exists() or MD_PATH.read_text(encoding="utf-8") != text:
            print("INVENTORY.md is not what inventory.json renders: run inventory_report.py", file=sys.stderr)
            return 1
        return 0
    MD_PATH.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
