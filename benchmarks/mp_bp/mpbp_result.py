"""Render `RESULT.md` from the aggregate gate reports in `results/`. Every number and every verdict sentence is read from
those JSON files; nothing is typed. Not part of the frozen scoring code: it reads reports, it never makes one.

    uv run --no-sync python benchmarks/mp_bp/mpbp_result.py --write benchmarks/mp_bp/RESULT.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
PROPS = (("normal_boiling_point", "Normal boiling point"), ("melting_point", "Melting point"))
MODELS = ("candidate_c", "marrero_gani", "joback")
LABEL = {"candidate_c": "Candidate C (Joback's groups, refit on development)", "marrero_gani": "Marrero-Gani first order",
         "joback": "Joback"}
# section 10: the published error each ceiling is 1.5x of
REFERENCE = {("joback", "normal_boiling_point"): 12.9, ("marrero_gani", "melting_point"): 24.9,
             ("marrero_gani", "normal_boiling_point"): 7.9, ("candidate_c", "melting_point"): 22.6,
             ("candidate_c", "normal_boiling_point"): 12.9}


def load(partition: str, prop: str, model: str) -> dict:
    return json.loads((RESULTS / f"{partition}_{prop}_{model}.json").read_text(encoding="utf-8"))


def _table(header, rows) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def _ci(v):
    return f"[{v[0]:.1f}, {v[1]:.1f}]"


def _row(r: dict, prop: str) -> list:
    m = r["metrics"]
    ref = REFERENCE.get((r["model"], prop))
    ceiling = f"{1.5 * ref:.2f}" if ref and r["gate_eligible"] else "none (proxy)" if not r["gate_eligible"] else "none"
    label = LABEL[r["model"]] + (" `tf`, as a proxy" if not r["gate_eligible"] else "")
    return [label, f"{r['counts']['entities_predicted']} / {r['counts']['entities_with_eligible_target']}",
            f"{r['coverage']:.0%}", f"{m['mae']:.1f} {_ci(m['mae_ci95'])}", ceiling, f"{m['baseline_mae_on_same_entities']:.1f}",
            f"{m['improvement_over_baseline']:+.0%} [{m['improvement_ci95'][0]:+.0%}, {m['improvement_ci95'][1]:+.0%}]",
            f"{m['bias']:+.1f}", r["leakage"]["status"], r["gate"]["evaluation_status"]]


def render() -> str:
    freeze = json.loads((RESULTS / "freeze.json").read_text(encoding="utf-8"))
    lock = (RESULTS / "holdout_scored.lock").read_text(encoding="utf-8").strip()
    holdout = {(p, m): load("holdout", p, m) for p, _ in PROPS for m in MODELS}
    chosen = ", ".join(prop.replace("_", " ") + " " + str(v) for prop, v in freeze["penalties"].items())
    out = [
        "# Melting / normal-boiling-point benchmark: result",
        "",
        ("Generated by `benchmarks/mp_bp/mpbp_result.py` from the reports in `results/`; every number below is read from "
        "them. The design, thresholds and amendments are in `PREREGISTRATION.md`; the corpus is described in "
        "`CORPUS_REPORT.md`. The reference values are copyrighted handbook tables and cannot be regenerated from this "
        "repository, and the handbooks contain printed errors (see `CORPUS_REPORT.md`): this measures agreement with "
        "handbook values."),
        "",
        "## What was examined, and when",
        "",
        (f"- Development and selection partitions: used to fit Candidate C, build the baseline and choose Candidate C's ridge penalty "
        f"(chosen: {chosen})."),
        (f"- Freeze: `{freeze['frozen_utc']}` at commit `{freeze['commit'][:8]}` (clean tree), hashing "
        f"{len(freeze['file_hashes'])} files that decide a score; manifest checksum `{freeze['manifest_checksum']}`."),
        f"- Holdout: scored once, `{lock}`. The lock file is in `results/`; the scorer refuses a second run.",
        "",
        "## Holdout (the preregistered evaluation)",
        "",
        ("Entities predicted / eligible, coverage, mean absolute error in K with its 95% bootstrap interval (entities resampled, 10,000 "
        "resamples), the preregistered ceiling (1.5 x the published error), the baseline's error on the same entities, the improvement over "
        "that baseline, signed bias (prediction minus handbook), the leakage status and the verdict."),
        "",
    ]
    for prop, title in PROPS:
        out += [f"### {title}", "", _table(
            ["method", "predicted / eligible", "coverage", "MAE (K)", "ceiling (K)", "baseline MAE", "improvement", "bias", "leakage", "verdict"],
            [_row(holdout[(prop, m)], prop) for m in MODELS]), ""]
    out += ["## Reading it", ""]
    for prop, title in PROPS:
        for m in MODELS:
            r = holdout[(prop, m)]
            g = r["gate"]
            sentence = f"- **{title}, {LABEL[m]}: {g['evaluation_status']}.** {g['reason']}."
            if g["evaluation_status"] == "NOT_EVALUABLE" and r["gate_eligible"]:
                sentence += (" On the numbers alone it " + ("**would meet** every numeric criterion" if g["numeric_criteria_all_met"]
                                                            else "would not meet the numeric criteria") +
                             "; with this leakage status that is exploratory and clears nothing.")
            out.append(sentence)
    out += ["", "## Label quality and sensitivity (holdout, secondary; not a gate)", "",
            _table(["property", "method", "MAE on all", "MAE where both books agree (n)", "MAE range over alternative observations"], [
                [title, LABEL[m], f"{holdout[(prop, m)]['metrics']['mae']:.1f}",
                 f"{holdout[(prop, m)]['label_quality_subset']['cross_source_agree_mae']:.1f} ({holdout[(prop, m)]['label_quality_subset']['cross_source_agree_n']})",
                 _ci(holdout[(prop, m)]['sensitivity']['mae_range_over_alternative_observations'])]
                for prop, title in PROPS for m in MODELS]), "",
            "## Development and selection (context; not claims)", "",
            "Candidate C is in-sample on development. Marrero-Gani and Joback were not fitted to this corpus.", ""]
    rows = []
    for prop, title in PROPS:
        for m in MODELS:
            cells = [title, LABEL[m]]
            for part in ("development", "selection", "holdout"):
                r = load(part, prop, m)
                cells.append(f"{r['metrics']['mae']:.1f} (n={r['counts']['entities_predicted']})")
            rows.append(cells)
    out += [_table(["property", "method", "development MAE", "selection MAE", "holdout MAE"], rows), "",
            "## Refusals on the holdout (coverage is reported against all eligible entities)", "",
            _table(["property", "method", "refusals"], [
                [title, LABEL[m], ", ".join(f"{k}: {v}" for k, v in sorted(holdout[(prop, m)]["refusals"].items())) or "none"]
                for prop, title in PROPS for m in MODELS]), "",
            "## Families on the holdout (a family under 30 entities supports no standalone claim)", ""]
    fam_rows = []
    for prop, title in PROPS:
        for m in MODELS:
            for fam, s in sorted(holdout[(prop, m)]["strata"].items()):
                fam_rows.append([title, LABEL[m], fam, s["n"], f"{s['mae']:.1f}", "yes" if s["claim_supported"] else "no"])
    out += [_table(["property", "method", "family", "n", "MAE", "claim supported"], fam_rows), "",
            "## What this allows", "",
            ("Nothing is promoted. A calculator for a property needs a PASS for that property; none was reached, and a proxy never promotes. "
            "No Marrero-Gani or Joback result can be an independent held-out claim, because neither paper lists its fit population "
            "(`PREREGISTRATION.md` section 9). No threshold was changed after any result was seen."), ""]
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--write", type=Path, required=True)
    args = ap.parse_args(argv)
    args.write.write_text(render(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
