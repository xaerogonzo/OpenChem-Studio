"""The Windows version resource of the executable, written for PyInstaller.

Until this existed `OpenChemStudio.exe` carried NO version information: right-click,
Properties, Details showed a blank product name, company and version. That is untidy for
users and disqualifying for code signing, which wants the signed file to say which product
and which version it is (SignPath Foundation's terms enforce both). The installer already
had them, from Inno Setup; this gives the exe the same, from the one version number in
`pyproject.toml`.

PyInstaller reads a version resource from a text file of `VSVersionInfo(...)`. That text is
produced here as plain strings, with no PyInstaller import, so it can be tested anywhere and
the spec only has to write it and pass the path.

NOT NAMED `packaging`-anything importable: `packaging/` is a folder of build files, not a
package, and a module of that name would collide with PyPI's `packaging`. The spec loads this
file by path.
"""

from __future__ import annotations

import re
from pathlib import Path

PRODUCT_NAME = "OpenChem Studio"
COMPANY_NAME = "OpenChem Studio"
DESCRIPTION = "OpenChem Studio"
INTERNAL_NAME = "OpenChemStudio"
ORIGINAL_FILENAME = "OpenChemStudio.exe"
COPYRIGHT = "Copyright (C) OpenChem Studio contributors. GPL-3.0-or-later."


def version_tuple(version: str) -> tuple[int, int, int, int]:
    """`0.10.0` -> `(0, 10, 0, 0)`; refuses anything but a plain dotted version."""
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise ValueError(f"not a plain dotted version: {version!r}")
    major, minor, patch = (int(part) for part in version.split("."))
    return major, minor, patch, 0


def render(version: str) -> str:
    """The text of a PyInstaller version file for `version`."""
    numbers = version_tuple(version)
    strings = [
        ("CompanyName", COMPANY_NAME),
        ("FileDescription", DESCRIPTION),
        ("FileVersion", version),
        ("InternalName", INTERNAL_NAME),
        ("LegalCopyright", COPYRIGHT),
        ("OriginalFilename", ORIGINAL_FILENAME),
        ("ProductName", PRODUCT_NAME),
        ("ProductVersion", version),
    ]
    rows = ",\n          ".join(f"StringStruct({key!r}, {value!r})" for key, value in strings)
    return (
        "# Generated by packaging/win_version_info.py from pyproject.toml -- do not edit.\n"
        "VSVersionInfo(\n"
        f"  ffi=FixedFileInfo(filevers={numbers!r}, prodvers={numbers!r}, mask=0x3f, flags=0x0,\n"
        "                    OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),\n"
        "  kids=[\n"
        "    StringFileInfo([StringTable('040904B0', [\n"
        f"          {rows}])]),\n"
        "    VarFileInfo([VarStruct('Translation', [1033, 1200])])\n"
        "  ]\n"
        ")\n"
    )


def write(path: Path, version: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(version), encoding="utf-8", newline="\n")
    return path
