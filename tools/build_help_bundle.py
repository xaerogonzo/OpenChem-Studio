"""Generate `src/openchem/_help_bundle.py`: the in-app help, inside the exe.

    uv run --no-sync python tools/build_help_bundle.py [--out PATH]

`build.ps1` runs this before freezing and deletes the result afterwards, the
way it does `_build_stamp.py`. The module holds three plain literals (schema,
digest, payload) and runs no code on import. The format and its reasons are in
`openchem/help.py`; this file only reads the documents that module names, so
there is still exactly one list of them.

Exits non-zero, writing nothing, if any help document is missing, empty or not
UTF-8: a bundle built from fewer documents would be a smaller help, silently.
"""

from __future__ import annotations

import argparse
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / "src" / "openchem" / "_help_bundle.py"

_TEMPLATE = '''# Generated by tools/build_help_bundle.py -- do not edit, do not commit.
SCHEMA = {schema}
DIGEST = "{digest}"
PAYLOAD = "{payload}"
'''


def render() -> str:
    """The module text for the documents currently on disk."""
    sys.path.insert(0, str(ROOT / "src"))
    from openchem import help as help_docs

    schema, digest, payload = help_docs.encode_bundle(help_docs.source_documents())
    return _TEMPLATE.format(schema=schema, digest=digest, payload=payload)


def write_atomically(path: Path, text: str) -> None:
    """Temp file beside the target, then replace: an interrupted run leaves no half module."""
    path.parent.mkdir(parents=True, exist_ok=True)
    handle, temporary = tempfile.mkstemp(dir=path.parent, prefix=path.name + ".", suffix=".tmp")
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
        os.replace(temporary, path)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    try:
        text = render()
    except Exception as exc:  # noqa: BLE001 - any failure must stop the build with a message
        print(f"build_help_bundle: {exc}", file=sys.stderr)
        return 1
    write_atomically(args.out, text)
    print(f"build_help_bundle: wrote {args.out} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
