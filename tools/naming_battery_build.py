def protocol_sha256() -> str:
    return hashlib.sha256(PROTOCOL.read_bytes()).hexdigest()


def load_protocol() -> dict:
    import tomllib

    return tomllib.loads(PROTOCOL.read_text(encoding="utf-8"))


# =====================================================================================================
# Rule-based generation: functional-group pairs. No lookup -- the SMILES IS the ground truth.
# =====================================================================================================

#: Every group's attachment fragment, split into what precedes ("before") and what follows ("after") the
#: propane-1,3-diyl backbone "CCC", so `before(A) + "CCC" + after(B)` is always a single valid SMILES for
#: the pair (A at C1, B at C3). Chosen so every fragment is a MINIMAL, unambiguous representative of its
#: group -- e.g. "ester" and "ether" use a methyl cap because a bare alkoxy/acyloxy needs a second carbon
#: to be a real ester/ether rather than a hydroxyl/alkoxide.
_GROUP_FRAGMENTS: dict[str, tuple[str, str]] = {
    "hydroxyl": ("O", "O"),
    "primary_amine": ("N", "N"),
    "carboxylic_acid": ("OC(=O)", "C(=O)O"),
    "ester": ("COC(=O)", "C(=O)OC"),
    "primary_amide": ("NC(=O)", "C(=O)N"),
    "nitrile": ("N#C", "C#N"),
    "chloro": ("Cl", "Cl"),
    "ether": ("CO", "OC"),
    "ketone": ("CC(=O)", "C(=O)C"),
    "aldehyde": ("O=C", "C=O"),
    "nitro": ("[O-][N+](=O)", "[N+](=O)[O-]"),
    "thiol": ("S", "S"),
}

_FALLBACK_BACKBONE = "CCCCCC"  # hexane-1,6-diyl, logged when used


def generate_functional_group_pairs(groups: list[str]) -> list[dict]:
    from rdkit import Chem

    missing = [g for g in groups if g not in _GROUP_FRAGMENTS]
    if missing:
        raise SystemExit(f"no fragment defined for group(s): {missing}")

    rows = []
    for a, b in itertools.combinations(groups, 2):
        before_a, _ = _GROUP_FRAGMENTS[a]
        _, after_b = _GROUP_FRAGMENTS[b]
        scaffold = "CCC"
        smiles = f"{before_a}{scaffold}{after_b}"
        mol = Chem.MolFromSmiles(smiles)
        used_fallback = False
        if mol is None:
            # The escape hatch the protocol promises: try the longer backbone before giving up.
            used_fallback = True
            scaffold = _FALLBACK_BACKBONE
            smiles = f"{before_a}{scaffold}{after_b}"
            mol = Chem.MolFromSmiles(smiles)
        if mol is None:
            raise SystemExit(f"functional_group_pairs: could not build a structure for ({a}, {b}): {smiles!r}")
        canonical = Chem.MolToSmiles(mol)
        rows.append(
            {
                "label": f"fgp-{a}+{b}",
                "category": "functional_group_pairs",
                "smiles": canonical,
                "source": "generated by rule",
                "provenance": {"groups": [a, b], "scaffold": "propane-1,3-diyl" if not used_fallback else "hexane-1,6-diyl (fallback)"},
            }
        )
    return rows


# =====================================================================================================
# Rule-based generation: salts. No lookup -- charge-balanced multi-component SMILES built directly.
# =====================================================================================================

_ION_SMILES: dict[str, tuple[str, int]] = {
    # name -> (SMILES, charge)
    "Na+": ("[Na+]", 1),
    "K+": ("[K+]", 1),
    "NH4+": ("[NH4+]", 1),
    "Ca2+": ("[Ca+2]", 2),
    "Mg2+": ("[Mg+2]", 2),
    "Fe3+": ("[Fe+3]", 3),
    "Cl-": ("[Cl-]", -1),
    "Br-": ("[Br-]", -1),
    "NO3-": ("[N+](=O)([O-])[O-]", -1),
    "SO4_2-": ("[O-]S(=O)(=O)[O-]", -2),
    "CO3_2-": ("[O-]C(=O)[O-]", -2),
    "PO4_3-": ("[O-]P(=O)([O-])[O-]", -3),
}

#: Only these reduced cation:anion ratios are built -- a genuine restriction, not an oversight: the
#: protocol commits to it before any salt is generated, so a combination needing e.g. 1:3 (FeCl3) is
#: dropped and counted rather than silently included with a different ratio rule applied after the fact.
_ALLOWED_RATIOS = {(1, 1), (1, 2), (2, 1)}


def _reduced_ratio(cation_charge: int, anion_charge: int) -> tuple[int, int]:
    import math

    a, c = abs(anion_charge), abs(cation_charge)
    g = math.gcd(a, c)
    return (a // g, c // g)  # (n_cations, n_anions)


def generate_salts(cations: list[str], anions: list[str]) -> tuple[list[dict], list[dict]]:
    from rdkit import Chem

    rows, dropped = [], []
    for cation_name, anion_name in itertools.product(cations, anions):
        cation_smiles, cation_charge = _ION_SMILES[cation_name]
        anion_smiles, anion_charge = _ION_SMILES[anion_name]
        n_cation, n_anion = _reduced_ratio(cation_charge, anion_charge)
        if (n_cation, n_anion) not in _ALLOWED_RATIOS:
            dropped.append(
                {
                    "cation": cation_name, "anion": anion_name,
                    "reason": f"needs a {n_cation}:{n_anion} ratio, outside {{1:1, 1:2, 2:1}}",
                }
            )
            continue
        smiles = ".".join([cation_smiles] * n_cation + [anion_smiles] * n_anion)
        mol = Chem.MolFromSmiles(smiles)
        if mol is None:
            raise SystemExit(f"salts: could not build {cation_name}/{anion_name}: {smiles!r}")
        canonical = Chem.MolToSmiles(mol)
        rows.append(
            {
                "label": f"salt-{cation_name}+{anion_name}",
                "category": "salts",
                "smiles": canonical,
                "source": "generated by rule",
                "provenance": {"cation": cation_name, "anion": anion_name, "ratio": f"{n_cation}:{n_anion}"},
            }
        )
    return rows, dropped


def cmd_generate(_args: argparse.Namespace) -> None:
    protocol = load_protocol()
    SCRATCH.mkdir(parents=True, exist_ok=True)

    fgp = generate_functional_group_pairs(protocol["category"]["functional_group_pairs"]["groups"])
    (SCRATCH / "functional_group_pairs.json").write_text(json.dumps(fgp, indent=1), encoding="utf-8")
    print(f"functional_group_pairs: {len(fgp)} rows -> {SCRATCH / 'functional_group_pairs.json'}")

    salt_cfg = protocol["category"]["salts"]
    salts, dropped = generate_salts(salt_cfg["cations"], salt_cfg["anions"])
    (SCRATCH / "salts.json").write_text(json.dumps(salts, indent=1), encoding="utf-8")
    (SCRATCH / "salts_dropped.json").write_text(json.dumps(dropped, indent=1), encoding="utf-8")
    print(f"salts: {len(salts)} rows ({len(dropped)} combinations dropped for ratio) -> {SCRATCH / 'salts.json'}")
    expected = salt_cfg["count"]
    if len(salts) != expected:
        print(
            f"  NOTE: protocol says count={expected}, generator produced {len(salts)}. "
            f"Update battery_r9_protocol.toml's [category.salts].count to match -- this is the actual, "
            f"computed charge-balance result, not a target to force the generator toward.",
            file=sys.stderr,
        )


# =====================================================================================================
# Rule-based generation: dipeptides. Built by rule, not looked up (protocol [category.amino_acids_and_peptides]).
# =====================================================================================================

#: Standard L-amino-acid side chains, as the fragment attached to the alpha carbon: `N[C@@H](R)C(=O)O`.
#: Glycine has no side chain (achiral alpha carbon) and proline's amino group is part of its own ring, so
#: both are handled separately below rather than forced into this shape. Internal stereocenters on
#: isoleucine and threonine's side chains are left unspecified -- this is a naming FIXTURE, not a claim
#: about which diastereomer; only the alpha carbon's L-configuration is asserted.
_SIDE_CHAINS: dict[str, str] = {
    "alanine": "C",
    "valine": "C(C)C",
    "leucine": "CC(C)C",
    "isoleucine": "C(C)CC",
    "phenylalanine": "Cc1ccccc1",
    "tryptophan": "Cc1c[nH]c2ccccc12",
    "methionine": "CCSC",
    "serine": "CO",
    "threonine": "C(O)C",
    "cysteine": "CS",
    "tyrosine": "Cc1ccc(O)cc1",
    "asparagine": "CC(N)=O",
    "glutamine": "CCC(N)=O",
    "aspartic acid": "CC(=O)O",
    "glutamic acid": "CCC(=O)O",
    "lysine": "CCCCN",
    "arginine": "CCCNC(=N)N",
    "histidine": "Cc1c[nH]cn1",
}

_PROLINE_AS_FIRST = "N1CCC[C@H]1C(=O)"     # ring N is already the free N-terminus; ends ready for the peptide bond
_PROLINE_AS_SECOND = "N1CCC[C@H]1C(=O)O"   # ring N becomes the amide nitrogen when concatenated after residue 1


def _residue_fragment(name: str, *, first: bool) -> str:
    if name == "glycine":
        return "NCC(=O)" if first else "NCC(=O)O"
    if name == "proline":
        return _PROLINE_AS_FIRST if first else _PROLINE_AS_SECOND
    side_chain = _SIDE_CHAINS[name]
    return f"N[C@@H]({side_chain})C(=O)" if first else f"N[C@@H]({side_chain})C(=O)O"


def generate_dipeptides(amino_acid_names: list[str], count: int, seed: int) -> list[dict]:
    """`count` seeded, unordered pairs from `amino_acid_names`, each built into a dipeptide by forming the
    peptide bond programmatically (residue 1's carbonyl to residue 2's amino nitrogen) -- never looked up."""
    import random

    from rdkit import Chem

    rng = random.Random(seed)
    pairs = list(itertools.combinations(sorted(amino_acid_names), 2))
    chosen = rng.sample(pairs, min(count, len(pairs)))

    rows = []
    for a, b in chosen:
        smiles = _residue_fragment(a, first=True) + _residue_fragment(b, first=False)
        mol = Chem.MolFromSmiles(smiles)
        if mol is None:
            raise SystemExit(f"dipeptides: could not build {a}-{b}: {smiles!r}")
        rows.append(
            {
                "label": f"dipeptide-{a}+{b}",
                "category": "amino_acids_and_peptides",
                "smiles": Chem.MolToSmiles(mol),
                "source": "generated by rule (peptide bond formed programmatically)",
                "provenance": {"residues": [a, b]},
            }
        )
    return rows


def cmd_dipeptides(_args: argparse.Namespace) -> None:
    protocol = load_protocol()
    SCRATCH.mkdir(parents=True, exist_ok=True)
    # Same 20 names the protocol lists for resolving -- see _AMINO_ACID_NAMES below.
    count = protocol["category"]["amino_acids_and_peptides"]["count"] - 20  # 40 total - 20 standalone AAs
    seed = 20260922
    rows = generate_dipeptides(_AMINO_ACID_NAMES, count, seed)
    (SCRATCH / "dipeptides.json").write_text(json.dumps(rows, indent=1), encoding="utf-8")
    print(f"dipeptides: {len(rows)} rows (seed {seed}) -> {SCRATCH / 'dipeptides.json'}")


